#[test]
fn an_aapcs64_save_area_is_a_variadic_tail() {
    let mut open = OpenProgram::of(
        Literal::of_code(
            AAPCS64,
            &[
                ("vf", BASE, 0x38),
                ("take", BASE + 0x38, 0x10),
                ("caller", BASE + 0x48, 0x10),
            ],
        )
        .in_aarch64(),
    );
    let callee = rendered(&mut open, BASE);
    assert!(callee.contains("vf(uint32_t arg0, ...)"), "{callee}");
    let caller = rendered(&mut open, BASE + 0x48);
    assert!(
        caller.contains("call to vf: variadic, its argument count unproven"),
        "{caller}"
    );
    assert!(!caller.contains("vf(1"), "{caller}");
}

